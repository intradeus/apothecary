// Package omp generates omp's (oh-my-pi) workspace config and says how to
// run it: omp is driven as a long-lived ACP agent (`omp acp`, verified
// against omp 18.13.1) through the workspace sidecar — see
// internal/adapters/acpagent.
//
// omp differs from opencode and codex in three ways that shape this package:
//   - in ACP mode it ignores every MCP config file, so ask_human rides each
//     session (Profile.MCPServers) instead of a generated config;
//   - its named agents are task subagents only — a session cannot start as
//     one — so a stage's role prompt is prepended to the first prompt, as for
//     codex (acpagent.RolePreamble);
//   - its credentials live in SQLite (agent.db), so a subscription login is
//     IMPORTED with `omp auth-broker import`, not written as a file.
//
// omp reports a cumulative USD cost per session (usage_update), so budgets
// work as for opencode.
package omp

import (
	"context"
	"encoding/json"
	"fmt"
	"path"
	"strings"

	"apothecary/internal/adapters/acpagent"
	"apothecary/internal/agentspec"
	"apothecary/internal/ports"
	"apothecary/internal/wshome"
)

type Config struct{}

type Adapter struct {
	envp ports.EnvProvisioner
	cfg  Config
}

func New(envp ports.EnvProvisioner, cfg Config) *Adapter {
	return &Adapter{envp: envp, cfg: cfg}
}

const (
	// defaultHome is the §8 pipeline image's workspace user. Repo-authored
	// devcontainers run the REPO's user instead, so the real home is probed
	// per env and this is only the fallback.
	defaultHome = "/home/apothecary"
)

// agentDir locates ~/.omp/agent in the home of the user omp actually runs
// as — under a hardcoded home the config and logins are silently invisible.
func (a *Adapter) agentDir(ctx context.Context, env ports.EnvID) string {
	return path.Join(wshome.Resolve(ctx, a.envp, env, defaultHome), ".omp", "agent")
}

// config is omp's global config.yml. --yolo already lifts the approval gate
// for the process; approvalMode says so again for a human running omp in the
// workspace terminal. Update and plugin checks are off: the workspace is
// rebuilt from a pinned version, never updated in place.
const config = `# Generated by apothecary. Regenerated every provision.
tools:
  approvalMode: yolo
startup:
  checkUpdate: false
marketplace:
  autoUpdate: "off"
`

// PrepareEnv generates omp-native config: config.yml, plus one role file per
// agent spec (delivered in-band, see the package doc). A flow's mcp_servers
// and ask_human are not here: omp reads no MCP config in ACP mode, so they
// all ride the session (acpagent).
func (a *Adapter) PrepareEnv(ctx context.Context, env ports.EnvID, specs []*agentspec.Spec) error {
	if err := acpagent.WriteRoles(ctx, a.envp, env, specs); err != nil {
		return err
	}
	if err := a.envp.WriteFile(ctx, env, path.Join(a.agentDir(ctx, env), "config.yml"), []byte(config), 0o644); err != nil {
		return fmt.Errorf("write config.yml: %w", err)
	}
	return nil
}

// AuthFilePath is the credential store SeedOAuth imports into, exposed so the
// engine can remove it when a run ends (the workspace outlives the run for
// inspection; the logins — refreshed by omp in place — should not).
func (a *Adapter) AuthFilePath(ctx context.Context, env ports.EnvID) string {
	return path.Join(a.agentDir(ctx, env), "agent.db")
}

// SeedOAuth imports subscription logins (CLIProxyAPI credential JSON, one
// document per login) into omp's agent.db: staged as files, imported by omp
// itself as the workspace user, then the staging directory is removed. A
// login omp skips (unknown type, unparseable expiry) fails the seed with
// omp's own reason rather than a run that later finds no provider.
func (a *Adapter) SeedOAuth(ctx context.Context, env ports.EnvID, creds [][]byte) error {
	if len(creds) == 0 {
		return nil
	}
	dir := path.Join(a.agentDir(ctx, env), "import")
	for i, c := range creds {
		if err := a.envp.WriteFile(ctx, env, path.Join(dir, fmt.Sprintf("%d.json", i)), c, 0o600); err != nil {
			return fmt.Errorf("stage login %d: %w", i, err)
		}
	}
	q := shellQuote(dir)
	res, err := a.envp.Exec(ctx, env, ports.Command{
		Script: "trap 'rm -rf " + q + "' EXIT; omp auth-broker import " + q + " --json",
	})
	if err != nil {
		return fmt.Errorf("import logins: %w", err)
	}
	if res.ExitCode != 0 {
		return fmt.Errorf("import logins: omp auth-broker import exited %d: %s", res.ExitCode, strings.TrimSpace(res.Output))
	}
	return importErrors(res.Output, len(creds))
}

// importErrors reads `omp auth-broker import --json`: a summary object
// naming the imported and skipped credentials. Every staged login must have
// been imported.
func importErrors(out string, want int) error {
	var sum struct {
		Imported []json.RawMessage `json:"imported"`
		Skipped  []struct {
			File   string `json:"file"`
			Reason string `json:"reason"`
		} `json:"skipped"`
	}
	for _, line := range strings.Split(out, "\n") {
		if line = strings.TrimSpace(line); strings.HasPrefix(line, "{") && json.Unmarshal([]byte(line), &sum) == nil {
			break
		}
	}
	if len(sum.Skipped) > 0 {
		var why []string
		for _, s := range sum.Skipped {
			why = append(why, path.Base(s.File)+": "+s.Reason)
		}
		return fmt.Errorf("import logins: omp skipped %s", strings.Join(why, "; "))
	}
	if len(sum.Imported) != want {
		return fmt.Errorf("import logins: omp imported %d of %d: %s", len(sum.Imported), want, strings.TrimSpace(out))
	}
	return nil
}

func shellQuote(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }

// --- running it ----------------------------------------------------------------

// Profile is how the ACP runner starts and addresses omp.
//
// --yolo: without an explicit approval mode omp's ACP mode still asks the
// client before every bash call. OMP_MCP_TIMEOUT_MS=0: ask_human blocks until
// the human answers (the engine parks the run if that takes too long, by
// cancelling the turn), and omp's 30 s per-call default would cut it short.
// OMP_SKIP_SETUP: never the first-run wizard.
func (a *Adapter) Profile() acpagent.Profile {
	return acpagent.Profile{
		Harness:  "omp",
		Command:  "env OMP_MCP_TIMEOUT_MS=0 OMP_SKIP_SETUP=1 omp acp --yolo",
		Preamble: acpagent.RolePreamble(a.envp, "omp"),
		MCPServers: []ports.MCPServer{
			{Name: "ask_human", Command: []string{"/opt/apothecary/shim", "ask-human"}},
		},
	}
}
