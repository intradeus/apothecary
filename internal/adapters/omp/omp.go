// Package omp generates omp's (oh-my-pi) workspace config and says how to
// run it: omp is driven as a long-lived ACP agent (`omp acp`, verified
// against omp 18.13.1) through the workspace sidecar — see
// internal/adapters/acpagent.
//
// omp differs from opencode and codex in three ways that shape this package:
//   - in ACP mode it ignores every MCP config file, so ask_human rides each
//     session (Profile.MCPServers) instead of a generated config;
//   - its named agents are task subagents only — a session cannot start as
//     one — so a stage's role prompt is prepended to the first prompt, as for
//     codex (acpagent.RolePreamble);
//   - its credentials live in SQLite (agent.db), so a subscription login is
//     IMPORTED with `omp auth-broker import`, not written as a file.
//
// omp reports a cumulative USD cost per session (usage_update), so budgets
// work as for opencode.
//
// A stage's harness options (harnessspec: advisor, smol, slow…) are per
// process in omp, so each distinct option set is its own `omp acp` process
// beside the base one, keyed by its config overlay's hash (RenderOptions).
package omp

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"path"
	"strings"

	"apothecary/internal/adapters/acpagent"
	"apothecary/internal/flow/agentspec"
	"apothecary/internal/flow/harnessspec"
	"apothecary/internal/ports/agentport"
	"apothecary/internal/ports/envport"
	"apothecary/internal/workspace/wshome"
)

type Config struct{}

type Adapter struct {
	envp envport.EnvProvisioner
	cfg  Config
}

func New(envp envport.EnvProvisioner, cfg Config) *Adapter {
	return &Adapter{envp: envp, cfg: cfg}
}

const (
	// defaultHome is a last-resort fallback: a repo-authored devcontainer
	// runs the REPO's user, so the real home is probed
	// per env and this is only the fallback.
	defaultHome = "/home/apothecary"
	// optionsDir holds the config overlays of stages' harness options:
	// engine-owned, like acpagent.RolesDir.
	optionsDir = "/apothecary/harness-options"
)

// agentDir locates ~/.omp/agent in the home of the user omp actually runs
// as — under a hardcoded home the config and logins are silently invisible.
func (a *Adapter) agentDir(ctx context.Context, env envport.EnvID) string {
	return path.Join(wshome.Resolve(ctx, a.envp, env, defaultHome), ".omp", "agent")
}

// config is omp's global config.yml. --yolo already lifts the approval gate
// for the process; approvalMode says so again for a human running omp in the
// workspace terminal. Update and plugin checks are off: the workspace is
// rebuilt from a pinned version, never updated in place.
const config = `# Generated by apothecary. Regenerated every provision.
tools:
  approvalMode: yolo
startup:
  checkUpdate: false
marketplace:
  autoUpdate: "off"
`

// InstallSkills copies the run's skills into ~/.omp/agent/skills, omp's
// native user-level skills directory. omp also reads the codex and
// opencode compat directories, where the same skills may sit when those
// harnesses share the project: same name, same bytes, and the native copy
// shadows the rest.
func (a *Adapter) InstallSkills(ctx context.Context, env envport.EnvID, names []string) error {
	return acpagent.InstallSkills(ctx, a.envp, env, path.Join(a.agentDir(ctx, env), "skills"), names)
}

// PrepareEnv generates omp-native config: config.yml, plus one role file per
// agent spec (delivered in-band, see the package doc). A flow's mcp_servers
// and ask_human are not here: omp reads no MCP config in ACP mode, so they
// all ride the session (acpagent).
func (a *Adapter) PrepareEnv(ctx context.Context, env envport.EnvID, specs []*agentspec.Spec) error {
	if err := acpagent.WriteRoles(ctx, a.envp, env, specs); err != nil {
		return err
	}
	if err := a.envp.WriteFile(ctx, env, path.Join(a.agentDir(ctx, env), "config.yml"), []byte(config), 0o644); err != nil {
		return fmt.Errorf("write config.yml: %w", err)
	}
	return nil
}

// AuthFilePath is omp's credential store (agent.db), exposed so the
// engine can remove it when a run ends (the workspace outlives the run for
// inspection; nothing in it should outlive the run).
func (a *Adapter) AuthFilePath(ctx context.Context, env envport.EnvID) string {
	return path.Join(a.agentDir(ctx, env), "agent.db")
}

// --- running it ----------------------------------------------------------------

// Profile is how the ACP runner starts and addresses omp.
//
// --yolo: without an explicit approval mode omp's ACP mode still asks the
// client before every bash call. OMP_MCP_TIMEOUT_MS=0: ask_human blocks until
// the human answers (the engine parks the run if that takes too long, by
// cancelling the turn), and omp's 30 s per-call default would cut it short.
// OMP_SKIP_SETUP: never the first-run wizard.
//
// A read-only session (the Ask pane's) is a second omp process beside the
// stage's: omp has no per-session mode and its named agents cannot start a
// session, but --tools loads only the tools named — none that writes a
// file or runs a shell — and --approval-mode=always-ask makes it ask the
// sidecar for anything else, which refuses. browser reads pages and drives
// the app, never the repository (it needs a Chromium the workspace may not
// have; then the tool simply fails). Pinned omp 18.13.1 takes these flags
// on `omp acp`; checked on 18.12.2.
func (a *Adapter) Profile() acpagent.Profile {
	return acpagent.Profile{
		Harness:  "omp",
		Command:  "env OMP_MCP_TIMEOUT_MS=0 OMP_SKIP_SETUP=1 omp acp --yolo",
		Preamble: acpagent.RolePreamble(a.envp, "omp"),
		MCPServers: []agentport.MCPServer{
			// The agent marker, explicitly: ask-human offers its tool only
			// below an agent, and this does not hang on omp passing its
			// own environment down (session-only, so no human's omp sees it).
			{Name: "ask_human", Command: []string{"/opt/apothecary/shim", "ask-human"}, Env: map[string]string{"APOTHECARY_AGENT": "1"}},
		},
		ReadOnlyBy:      acpagent.ReadOnlyByProcess,
		ReadOnlyCommand: "env OMP_MCP_TIMEOUT_MS=0 OMP_SKIP_SETUP=1 omp acp --tools=" + readOnlyTools + " --approval-mode=always-ask",
		OptionArgs:      a.options,
	}
}

// RenderOptions turns a stage's omp options into the config overlay omp loads
// with --config, and the flags that go with it. The overlay is JSON (YAML
// reads it), so no value is ever spliced into YAML or a command line.
//
// --advisor is a flag, not advisor.enabled: a runtime override wins over the
// setting's ACP protocol default (off) whatever the overlay's precedence.
// modelRoles has no protocol default, so the overlay carries it.
func RenderOptions(opts map[string]string) (overlay []byte, flags []string, err error) {
	roles := map[string]string{}
	advisor := map[string]string{}
	for k, v := range opts {
		switch k {
		case harnessspec.OmpAdvisor:
			roles["advisor"] = v
			flags = []string{"--advisor"}
		case harnessspec.OmpAdvisorReview:
			advisor["reviewMode"] = v
		case harnessspec.OmpSmol:
			roles["smol"] = v
		case harnessspec.OmpSlow:
			roles["slow"] = v
		default:
			return nil, nil, fmt.Errorf("omp: unknown harness option %q", k)
		}
	}
	doc := map[string]any{}
	if len(roles) > 0 {
		doc["modelRoles"] = roles
	}
	if len(advisor) > 0 {
		doc["advisor"] = advisor
	}
	overlay, err = json.Marshal(doc) // map keys sort: one option set, one overlay
	return overlay, flags, err
}

// options writes a stage's overlay where omp can read it, named by its hash
// so the same options always give the same command line — and so reach the
// same process (acpagent.Profile.OptionArgs).
func (a *Adapter) options(ctx context.Context, env envport.EnvID, opts map[string]string) (string, error) {
	overlay, flags, err := RenderOptions(opts)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(overlay)
	p := path.Join(optionsDir, "omp-"+hex.EncodeToString(sum[:6])+".yml")
	if err := a.envp.WriteFile(ctx, env, p, overlay, 0o644); err != nil {
		return "", fmt.Errorf("write %s: %w", p, err)
	}
	return strings.Join(append([]string{"--config=" + p}, flags...), " "), nil
}

// readOnlyTools are omp's built-in tools a read-only session loads: reading
// and searching the repository, and the web. omp has no built-in "browser"
// tool — naming an unknown tool fails session/new outright.
const readOnlyTools = "read,grep,glob,web_search"
