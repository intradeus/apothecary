// Package codex adapts the AgentRunner port to the codex CLI (DESIGN2
// §13), executing inside workspaces through the EnvProvisioner.
//
// Verified against codex-cli 0.144.6 (flags + JSONL probed live; behavior,
// not flags, is normative):
//
//	cat <role> <prompt> | codex exec --json -m <model> \
//	    --dangerously-bypass-approvals-and-sandbox --skip-git-repo-check -
//
// The bypass flag is codex's documented mode for "environments that are
// externally sandboxed" — exactly the factory workspace (container +
// default-deny firewall). codex reads the prompt from stdin (`-`): the
// role preamble and the §3.2 engine prompt are piped in, which also avoids
// arg-size limits. The --json stream is JSONL:
//
//	{"type":"thread.started","thread_id":"<uuid>"}   -> SessionID
//	{"type":"turn.completed","usage":{...}}          -> TurnsUsed/Usage
//	{"type":"item.completed","item":{"type":"agent_message","text":...}}
//
// codex reports token counts but no dollar cost -> CostUSD stays 0 and
// budgets ride max_total_turns (§3 anticipated this). Resume maps to
// `codex exec resume <thread_id> -` with the reply piped in.
package codex

import (
	"context"
	"encoding/json"
	"fmt"
	"path"
	"strings"

	"apothecary/internal/agentspec"
	"apothecary/internal/ports"
)

type Config struct{}

type Adapter struct {
	envp ports.EnvProvisioner
	cfg  Config
}

func New(envp ports.EnvProvisioner, cfg Config) *Adapter {
	return &Adapter{envp: envp, cfg: cfg}
}

const (
	promptPath = "/apothecary/prompt.txt"
	replyPath  = "/apothecary/reply.txt"
	rolesDir   = "/apothecary/agents"
	codexHome  = "/home/apothecary/.codex"
	authPath   = codexHome + "/auth.json"
	configPath = codexHome + "/config.toml"
)

// PrepareEnv generates codex-native config (§13): config.toml registering
// the ask_human MCP server, plus one role file per .apothecary/agents spec —
// codex has no named-agent registry, so the role prompt is delivered
// in-band as a prompt preamble (mechanism recorded in IMPLEMENTATION_NOTES).
func (a *Adapter) PrepareEnv(ctx context.Context, env ports.EnvID, specs []*agentspec.Spec) error {
	for _, s := range specs {
		if err := a.envp.WriteFile(ctx, env, path.Join(rolesDir, s.Name+".role"), []byte(roleText(s)), 0o644); err != nil {
			return fmt.Errorf("write role %s: %w", s.Name, err)
		}
	}
	cfg := `# Generated by apothecary. Regenerated every provision.
[mcp_servers.ask_human]
command = "/opt/apothecary/shim"
args = ["ask-human"]
`
	if err := a.envp.WriteFile(ctx, env, configPath, []byte(cfg), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}

// SeedAuthJSON writes codex's auth.json (ChatGPT-login artifact) into
// $CODEX_HOME; API-key auth rides OPENAI_API_KEY via provider.env instead.
func (a *Adapter) SeedAuthJSON(ctx context.Context, env ports.EnvID, data []byte) error {
	if len(data) == 0 {
		return nil
	}
	if err := a.envp.WriteFile(ctx, env, authPath, data, 0o600); err != nil {
		return fmt.Errorf("seed auth.json: %w", err)
	}
	return nil
}

// roleText renders the in-band system preamble. read_only/allow_bash are
// instruction-level only for codex — weaker than opencode's tool config; a
// documented residual (§13), mitigated as ever by human review of the
// branch.
func roleText(s *agentspec.Spec) string {
	var b strings.Builder
	b.WriteString("# ROLE\n")
	b.WriteString(strings.TrimSpace(s.Prompt))
	b.WriteString("\n")
	if s.ReadOnly {
		b.WriteString("\nIMPORTANT: This role is READ-ONLY with respect to the repository: do not modify, create or delete repository files except the explicitly required output artifacts.\n")
	}
	if !s.AllowBash {
		b.WriteString("Do not run shell commands for this task.\n")
	}
	b.WriteString("\n")
	return b.String()
}

// --- AgentRunner ------------------------------------------------------------

// codexModel strips the flow's provider prefix: flows say `openai/gpt-5-…`
// (provider/model, §3), codex wants the bare model id.
func codexModel(m string) string {
	if _, rest, ok := strings.Cut(m, "/"); ok {
		return rest
	}
	return m
}

func (a *Adapter) Run(ctx context.Context, env ports.EnvID, spec ports.AgentSpec, in ports.AgentInput) (ports.AgentResult, error) {
	if err := a.envp.WriteFile(ctx, env, promptPath, []byte(in.Prompt), 0o600); err != nil {
		return ports.AgentResult{}, fmt.Errorf("write prompt: %w", err)
	}
	// shellQuote, not %q: Go's %q double-quotes, inside which the shell
	// still expands $ and backticks (a model string like `openai/$(cmd)`
	// would execute).
	script := fmt.Sprintf(
		`set -a; [ -f /apothecary/provider.env ] && . /apothecary/provider.env; [ -s /apothecary/proxy.env ] && . /apothecary/proxy.env; set +a
cat %s %s | codex exec --json -m %s --dangerously-bypass-approvals-and-sandbox --skip-git-repo-check -`,
		shellQuote(path.Join(rolesDir, spec.Agent+".role")), shellQuote(promptPath), shellQuote(codexModel(spec.Model)))
	return a.invoke(ctx, env, script)
}

func (a *Adapter) Resume(ctx context.Context, env ports.EnvID, session ports.SessionID, reply string) (ports.AgentResult, error) {
	if session == "" {
		return ports.AgentResult{}, fmt.Errorf("codex resume: no session recorded for this stage (thread.started was never seen)")
	}
	if err := a.envp.WriteFile(ctx, env, replyPath, []byte(reply), 0o600); err != nil {
		return ports.AgentResult{}, fmt.Errorf("write reply: %w", err)
	}
	script := fmt.Sprintf(
		`set -a; [ -f /apothecary/provider.env ] && . /apothecary/provider.env; [ -s /apothecary/proxy.env ] && . /apothecary/proxy.env; set +a
cat %s | codex exec resume %s --json --dangerously-bypass-approvals-and-sandbox --skip-git-repo-check -`,
		shellQuote(replyPath), shellQuote(string(session)))
	return a.invoke(ctx, env, script)
}

// shellQuote single-quotes s for POSIX sh (inert $, backticks, spaces).
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

func (a *Adapter) invoke(ctx context.Context, env ports.EnvID, script string) (ports.AgentResult, error) {
	res, err := a.envp.Exec(ctx, env, ports.Command{Script: script, Dir: "repo"})
	if err != nil {
		return ports.AgentResult{}, err
	}
	result := parseEvents(res.Output)
	if res.ExitCode != 0 {
		// Same lesson as opencode: failed invocations must surface the RAW
		// output in logs and the on_fail feed.
		result.Output = res.Output
		return result, fmt.Errorf("codex exit %d: %s", res.ExitCode, tail(res.Output, 2048))
	}
	return result, nil
}

// event mirrors the --json JSONL stream (codex-cli 0.144.6).
type event struct {
	Type     string `json:"type"`
	ThreadID string `json:"thread_id"`
	Usage    struct {
		InputTokens       int `json:"input_tokens"`
		CachedInputTokens int `json:"cached_input_tokens"`
		OutputTokens      int `json:"output_tokens"`
	} `json:"usage"`
	Item struct {
		Type string `json:"type"`
		Text string `json:"text"`
	} `json:"item"`
}

// parseEvents folds the JSONL stream into an AgentResult. Non-JSON lines
// (codex's own tracing logs interleave) are skipped.
func parseEvents(output string) ports.AgentResult {
	var r ports.AgentResult
	var texts []string
	for line := range strings.SplitSeq(output, "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "{") {
			continue
		}
		var ev event
		if err := json.Unmarshal([]byte(line), &ev); err != nil {
			continue
		}
		switch ev.Type {
		case "thread.started":
			if ev.ThreadID != "" {
				r.Session = ports.SessionID(ev.ThreadID)
			}
		case "turn.completed":
			r.TurnsUsed++
			r.Usage.InputTokens += ev.Usage.InputTokens + ev.Usage.CachedInputTokens
			r.Usage.OutputTokens += ev.Usage.OutputTokens
			// CostUSD stays 0: codex reports tokens, not dollars (§13).
		case "item.completed":
			if ev.Item.Type == "agent_message" && ev.Item.Text != "" {
				texts = append(texts, ev.Item.Text)
			}
		}
	}
	r.Output = strings.Join(texts, "\n")
	return r
}

func tail(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[len(s)-n:]
}

var _ ports.AgentRunner = (*Adapter)(nil)
