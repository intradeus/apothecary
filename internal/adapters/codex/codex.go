// Package codex generates codex's workspace config (roles, the ask_human MCP
// server, auth) and says how to run it: codex is driven as a long-lived ACP
// agent through the ACP bridge (`codex-acp`, @agentclientprotocol/codex-acp)
// hosted by the workspace sidecar — see internal/adapters/acpagent.
//
// The session runs in the bridge's "agent-full-access" mode: no approval
// prompts and no inner codex sandbox, codex's documented posture for
// environments that are externally sandboxed — exactly the factory
// workspace (container + egress gateway). codex has no named-agent
// registry, so a stage's role prompt is prepended to the session's first
// prompt. codex reports tokens but no dollar cost, so CostUSD stays 0 and
// budgets ride max_total_turns.
package codex

import (
	"context"
	"fmt"
	"path"
	"strings"

	"apothecary/internal/adapters/acpagent"
	"apothecary/internal/agentspec"
	"apothecary/internal/ports"
	"apothecary/internal/wshome"
)

type Config struct{}

type Adapter struct {
	envp ports.EnvProvisioner
	cfg  Config
}

func New(envp ports.EnvProvisioner, cfg Config) *Adapter {
	return &Adapter{envp: envp, cfg: cfg}
}

const (
	rolesDir = "/apothecary/agents"
	// defaultHome is the §8 pipeline image's workspace user. Repo-authored
	// devcontainers run the REPO's user instead, so the real home is probed
	// per env and this is only the fallback.
	defaultHome = "/home/apothecary"
)

// codexHome locates .codex in the home of the user codex actually runs as —
// under a hardcoded home the config and auth are silently invisible to it.
func (a *Adapter) codexHome(ctx context.Context, env ports.EnvID) string {
	return path.Join(wshome.Resolve(ctx, a.envp, env, defaultHome), ".codex")
}

// PrepareEnv generates codex-native config (§13): config.toml registering
// the ask_human MCP server, plus one role file per .apothecary/agents spec —
// codex has no named-agent registry, so the role prompt is delivered
// in-band as a prompt preamble (mechanism recorded in IMPLEMENTATION_NOTES).
// A flow's mcp_servers are not here: a stage's ride its ACP session
// (acpagent), and codex-acp keeps a session's servers to that session, so
// each agent sees only its own.
func (a *Adapter) PrepareEnv(ctx context.Context, env ports.EnvID, specs []*agentspec.Spec) error {
	for _, s := range specs {
		if err := a.envp.WriteFile(ctx, env, path.Join(rolesDir, s.Name+".role"), []byte(roleText(s)), 0o644); err != nil {
			return fmt.Errorf("write role %s: %w", s.Name, err)
		}
	}
	// tool_timeout_sec: ask_human blocks until the human answers (the
	// engine parks the run if that takes too long, by cancelling the turn),
	// so codex's 60 s default per tool call must not cut it short.
	cfg := `# Generated by apothecary. Regenerated every provision.
approval_policy = "never"
sandbox_mode = "danger-full-access"

[mcp_servers.ask_human]
command = "/opt/apothecary/shim"
args = ["ask-human"]
tool_timeout_sec = 86400
`
	if err := a.envp.WriteFile(ctx, env, path.Join(a.codexHome(ctx, env), "config.toml"), []byte(cfg), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}

// AuthFilePath is where SeedAuthJSON puts the credential, exposed so the
// engine can remove it when a run ends (the workspace outlives the run for
// inspection; the ChatGPT-login tokens should not).
func (a *Adapter) AuthFilePath(ctx context.Context, env ports.EnvID) string {
	return path.Join(a.codexHome(ctx, env), "auth.json")
}

// SeedAuthJSON writes codex's auth.json (ChatGPT-login artifact) into
// $CODEX_HOME; API-key auth rides OPENAI_API_KEY via provider.env instead.
func (a *Adapter) SeedAuthJSON(ctx context.Context, env ports.EnvID, data []byte) error {
	if len(data) == 0 {
		return nil
	}
	if err := a.envp.WriteFile(ctx, env, path.Join(a.codexHome(ctx, env), "auth.json"), data, 0o600); err != nil {
		return fmt.Errorf("seed auth.json: %w", err)
	}
	return nil
}

// roleText renders the in-band system preamble. read_only/allow_bash are
// instruction-level only for codex — weaker than opencode's tool config; a
// documented residual (§13), mitigated as ever by human review of the
// branch.
func roleText(s *agentspec.Spec) string {
	var b strings.Builder
	b.WriteString("# ROLE\n")
	b.WriteString(strings.TrimSpace(s.Prompt))
	b.WriteString("\n")
	if s.ReadOnly {
		b.WriteString("\nIMPORTANT: This role is READ-ONLY with respect to the repository: do not modify, create or delete repository files except the explicitly required output artifacts.\n")
	}
	if !s.AllowBash {
		b.WriteString("Do not run shell commands for this task.\n")
	}
	b.WriteString("\n")
	return b.String()
}

// --- running it ----------------------------------------------------------------

// fullAccessMode is codex-acp's session mode without approvals or sandbox.
const fullAccessMode = "agent-full-access"

// Profile is how the ACP runner starts and addresses codex.
func (a *Adapter) Profile() acpagent.Profile {
	return acpagent.Profile{
		Harness: "codex",
		Command: "codex-acp",
		Mode:    func(ports.AgentSpec) string { return fullAccessMode },
		Preamble: func(ctx context.Context, env ports.EnvID, spec ports.AgentSpec) (string, error) {
			if spec.Agent == "" {
				return "", nil
			}
			role, err := a.envp.ReadFile(ctx, env, path.Join(rolesDir, spec.Agent+".role"))
			if err != nil {
				return "", fmt.Errorf("codex: role for agent %q: %w", spec.Agent, err)
			}
			return string(role), nil
		},
	}
}
