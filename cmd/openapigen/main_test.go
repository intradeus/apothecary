// TestMain lets a test run the real main in a child process, where its exits
// are what an operator's shell sees.
func TestMain(m *testing.M) {
	if raw := os.Getenv("OPENAPIGEN_TEST_ARGV"); raw != "" {
		var argv []string
		if err := json.Unmarshal([]byte(raw), &argv); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(3)
		}
		os.Args = append([]string{"openapigen"}, argv...)
		main()
		os.Exit(0)
	}
	os.Exit(m.Run())
}

func child(t *testing.T, args ...string) (stdout, stderr string, code int) {
	t.Helper()
	argv, err := json.Marshal(args)
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(os.Args[0])
	// GOCOVERDIR: a binary built with -cover warns on stderr without it.
	cmd.Env = []string{"OPENAPIGEN_TEST_ARGV=" + string(argv), "GOCOVERDIR=" + t.TempDir()}
	var out, errb strings.Builder
	cmd.Stdout, cmd.Stderr = &out, &errb
	if err := cmd.Run(); err != nil {
		ee, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatal(err)
		}
		code = ee.ExitCode()
	}
	return out.String(), errb.String(), code
}

// inProcess runs main here, for the paths that return, and gives back what it
// printed.
func inProcess(t *testing.T, args ...string) string {
	t.Helper()
	oldArgs, oldFlags, oldOut := os.Args, flag.CommandLine, os.Stdout
	defer func() { os.Args, flag.CommandLine, os.Stdout = oldArgs, oldFlags, oldOut }()
	os.Args = append([]string{"openapigen"}, args...)
	flag.CommandLine = flag.NewFlagSet("openapigen", flag.ContinueOnError)
	r, w, err := os.Pipe()
	if err != nil {
		t.Fatal(err)
	}
	os.Stdout = w
	main()
	w.Close()
	out, _ := io.ReadAll(r)
	return string(out)
}

func TestWritesTheDocument(t *testing.T) {
	path := filepath.Join(t.TempDir(), "openapi.yaml")
	out := inProcess(t, "-o", path)
	if !strings.Contains(out, "wrote "+path) || !strings.Contains(out, "paths)") {
		t.Errorf("output = %q", out)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(data), "# Generated by cmd/openapigen") {
		t.Errorf("no generated banner: %.80s", data)
	}
	var doc struct {
		OpenAPI string         `yaml:"openapi"`
		Paths   map[string]any `yaml:"paths"`
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(doc.OpenAPI, "3.") || doc.Paths["/api/runs/{id}"] == nil {
		t.Errorf("document = %q with %d paths", doc.OpenAPI, len(doc.Paths))
	}
}

// -check is what CI runs: quiet and zero when current, and a stale or missing
// file fails with the command that fixes it, never rewriting anything.
func TestCheck(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "openapi.yaml")
	inProcess(t, "-o", path)

	if out := inProcess(t, "-check", "-o", path); out != "" {
		t.Errorf("current file printed %q", out)
	}
	if _, stderr, code := child(t, "-check", "-o", path); code != 0 || stderr != "" {
		t.Errorf("current file = exit %d, %q", code, stderr)
	}

	if err := os.WriteFile(path, []byte("stale\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, stderr, code := child(t, "-check", "-o", path)
	if code != 1 || !strings.Contains(stderr, "out of date") || !strings.Contains(stderr, "task api:spec") {
		t.Errorf("stale = exit %d, %q", code, stderr)
	}
	if got, _ := os.ReadFile(path); string(got) != "stale\n" {
		t.Errorf("-check rewrote the file: %.40s", got)
	}

	_, stderr, code = child(t, "-check", "-o", filepath.Join(dir, "missing.yaml"))
	if code != 1 || !strings.Contains(stderr, "is missing") {
		t.Errorf("missing = exit %d, %q", code, stderr)
	}
}

func TestWriteFailureExits(t *testing.T) {
	_, stderr, code := child(t, "-o", filepath.Join(t.TempDir(), "no", "such", "dir", "openapi.yaml"))
	if code != 1 || !strings.HasPrefix(stderr, "openapigen:") {
		t.Errorf("exit %d, %q", code, stderr)
	}
}
